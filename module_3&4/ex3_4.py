no1 = int(input("Please enter the first number: "))
no2 = int(input("Please enter the second number: "))
no3 = int(input("Please enter the third number: "))
sum = no1 + no2 + no3
prod = no1 * no2 * no3
avg = sum / 3
print(f"The sum of the three numbers is: {sum}")
print(f"The product of the three numbers is: {prod}")
print(f"The average of the three numbers is: {avg}")